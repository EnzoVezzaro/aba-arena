/** agents/default.md — project-aware default agent profile. */
function agentProfile(repoName, languages) {
  return `# default.md — Default Agent Profile

Agent profile for a coding agent working in ${repoName}.

## Operating rules

1. **Start from the contracts.** Read the root AGENTS.md, then the AGENTS.md
   of the functionality you are working in, before editing anything.
2. **Follow the control plane.** Procedures live in
   \`.acc/config/workflows/\`; standards in \`.acc/config/standards/\`.
3. **Use the acc CLI for focused context.** \`acc context <dir>\`,
   \`acc graph\`, \`acc dependencies <dir>\`, \`acc impact <dir>\`.
4. **Record durable knowledge.** After significant work, run
   \`acc memory add <dir> "<what you learned>"\`.
5. **Validate before finishing.** Run \`acc check\` and fix every
   error-level diagnostic.

## Project facts

- Name: ${repoName}
- Languages: ${languages.length > 0 ? languages.join(', ') : 'n/a'}
- Every functionality directory carries its own AGENTS.md contract and
  .acc-memory.md log.
`;
}

/** standards/*.md — project-aware architecture, coding, and review docs. */
function standardsDocs(repoName, languages) {
  const langs = languages.length > 0 ? languages.join(', ') : 'n/a';
  return {
    'architecture.md': `# architecture.md — Architecture Standards

${repoName} is organized as ACC functionality boundaries: each meaningful
directory owns an AGENTS.md contract declaring its purpose, ownership,
dependencies, and constraints. The derived architecture graph
(\`acc graph\`) is the authoritative map of boundaries and relationships.

## Rules

- A functionality's code lives in its own directory, documented by that
  directory's AGENTS.md.
- Cross-boundary dependencies are declared in the Dependencies section of
  the source boundary's contract.
- New boundaries follow \`.acc/config/workflows/feature.md\`; structural
  changes follow \`.acc/config/workflows/refactor.md\`.
`,
    'coding.md': `# coding.md — Coding Standards

Coding standards for ${repoName} (languages: ${langs}).

## Rules

- Match the existing style of the file you edit.
- Prefer small, single-purpose functions and modules.
- Do not introduce dependencies that are not declared in the boundary's
  AGENTS.md Dependencies section.
- Never commit secrets, credentials, or build artifacts.
- Update the relevant AGENTS.md when behavior or boundaries change.
`,
    'review.md': `# review.md — Review Checklist

Review checklist for changes to ${repoName}.

## Checklist

- [ ] \`acc check\` passes with zero error-level diagnostics.
- [ ] Every changed functionality's AGENTS.md reflects the new behavior,
      ownership, and dependencies.
- [ ] Durable knowledge was recorded with
      \`acc memory add <dir> "..."\`.
- [ ] The project's own tests/build pass.
- [ ] No secrets, build artifacts, or large binaries are committed.
`,
  };
}

/**
 * Write the complete .acc/config/ set (additive). Returns
 * { config, agents, standards, languages, ignore }.
 */
function writeAccConfig(root, repoName, opts = {}) {
  const configDir = path.join(root, '.acc', 'config');
  fs.mkdirSync(configDir, { recursive: true });
  const result = {
    config: false,
    agents: [],
    standards: [],
    languages: detectLanguages(root),
    ignore: detectIgnoredDirs(root),
  };

  // config.yaml — replaced only when ABA just scaffolded it (opts.overwriteConfig).
  const configFile = path.join(configDir, 'config.yaml');
  if (opts.overwriteConfig || !fs.existsSync(configFile)) {
    fs.writeFileSync(configFile, generateConfigYaml(repoName, result.languages, result.ignore), 'utf8');
    result.config = true;
  }

  const agentsDir = path.join(configDir, 'agents');
  fs.mkdirSync(agentsDir, { recursive: true });
  const profileFile = path.join(agentsDir, 'default.md');
  if (!fs.existsSync(profileFile)) {
    fs.writeFileSync(profileFile, agentProfile(repoName, result.languages), 'utf8');
    result.agents.push('default.md');
  }

  const standardsDir = path.join(configDir, 'standards');
  fs.mkdirSync(standardsDir, { recursive: true });
  for (const [name, content] of Object.entries(standardsDocs(repoName, result.languages))) {
    const f = path.join(standardsDir, name);
    if (!fs.existsSync(f)) {
      fs.writeFileSync(f, content, 'utf8');
      result.standards.push(name);
    }
  }

  // The docs' full control plane also has skills/, mcp/, tools/, and
  // multi-agent/ — scaffold each with a README documenting its purpose.
  result.controlPlane = [];
  for (const [name, readme] of Object.entries(CONTROL_PLANE_DIRS)) {
    const dir = path.join(configDir, name);
    fs.mkdirSync(dir, { recursive: true });
    const f = path.join(dir, 'README.md');
    if (!fs.existsSync(f)) {
      fs.writeFileSync(f, readme, 'utf8');
      result.controlPlane.push(name);
    }
  }

  return result;
}

/**
 * Verify the repo is FULLY ACC documented. Returns a list of problems
 * (empty = complete). Checks: config present with every setting, agents/
 * standards/ workflows/ populated, every content folder contracted, every
 * contract complete (acc fill), every contract with a filled memory file.
 */
async function verifyAccDocumented(root, runAcc) {
  const problems = [];

  // 1. Control plane files.
  const configFile = path.join(root, '.acc', 'config', 'config.yaml');
  if (!fs.existsSync(configFile)) {
    problems.push('.acc/config/config.yaml is missing');
  } else {
    let text = '';
    try {
      text = fs.readFileSync(configFile, 'utf8');
    } catch {
      text = '';
    }
    for (const key of CONFIG_KEYS) {
      if (!text.includes(`${key}:`)) problems.push(`config.yaml is missing the '${key}' setting`);
    }
  }
  for (const dir of ['agents', 'standards', 'workflows', 'skills', 'mcp', 'tools', 'multi-agent']) {
    const d = path.join(root, '.acc', 'config', dir);
    let hasMd = false;
    try {
      hasMd = fs.readdirSync(d).some((f) => f.endsWith('.md'));
    } catch {
      hasMd = false;
    }
    if (!hasMd) problems.push(`.acc/config/${dir}/ has no files`);
  }


  // 2. Every content folder has a contract.
  const missingDirs = missingContractDirs(root);
  for (const dir of missingDirs) problems.push(`${dir} lacks an AGENTS.md contract`);

  // 3. Every contract is complete (no placeholders).
  const fill = await runAcc(['fill', '--json'], root);
  try {
    const summary = JSON.parse(fill.out).result?.summary;
    if (summary && summary.draft > 0) {
      problems.push(`${summary.draft} AGENTS.md contract${summary.draft === 1 ? '' : 's'} still incomplete`);
    }
  } catch {
    // non-JSON output — fall through
  }

  // 4. Every contract has a filled .acc-memory.md.
  const missingMemory = missingMemoryFiles(root);
  if (missingMemory.length > 0) {
    problems.push(`${missingMemory.length} contract${missingMemory.length === 1 ? '' : 's'} lack a filled .acc-memory.md`);
  }

  return problems;
}

module.exports = {
  ANALYZER_EXTS,
  CONFIG_KEYS,
  CONTROL_PLANE_DIRS,
  detectLanguages,
  detectIgnoredDirs,
  generateConfigYaml,
  writeAccConfig,
  verifyAccDocumented,
};
