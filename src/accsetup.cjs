'use strict';

/**
 * Project-aware ACC configuration generation (the `.acc/config/` control
 * plane) + the final "is the repo fully ACC documented?" verification.
 *
 * `acc init` scaffolds only a minimal config.yaml and EMPTY agents/,
 * workflows/, standards/ directories. ABA completes them from the loaded
 * repository so the ACC panel fights with the framework fully configured:
 *
 *   - config.yaml      → every setting the framework reads (mirrors
 *                        acc-agents/lib/config.js DEFAULTS), with language
 *                        analyzers enabled for the languages actually present
 *                        and ignore lists for the repo's build noise.
 *   - agents/default.md → a project-aware default agent profile.
 *   - standards/*.md   → architecture, coding, and review standards.
 *
 * All writes are additive — a repo's own .acc/config/ content is never
 * overwritten, except the minimal config.yaml when ABA just scaffolded it
 * (opts.overwriteConfig).
 */

const fs = require('fs');
const path = require('path');
const { missingContractDirs, missingMemoryFiles } = require('./accfill.cjs');

// Mirrors acc-agents/lib/diagnostics.js ANALYZER_EXTS — keep in sync.
const ANALYZER_EXTS = {
  rust: ['.rs'],
  typescript: ['.ts', '.tsx', '.mts', '.cts'],
  go: ['.go'],
  python: ['.py', '.pyi'],
  java: ['.java'],
  csharp: ['.cs'],
  cpp: ['.c', '.h', '.cpp', '.hpp', '.cc', '.cxx'],
  ruby: ['.rb'],
  php: ['.php'],
  swift: ['.swift'],
  kotlin: ['.kt', '.kts'],
  javascript: ['.js', '.jsx', '.mjs', '.cjs'],
};

// Directories always excluded from ACC walks (VCS, deps, build noise).
const DEFAULT_IGNORE = ['node_modules', 'dist', 'build', 'coverage'];

// Top-level config.yaml settings — mirrors acc-agents/lib/config.js DEFAULTS.
const CONFIG_KEYS = [
  'schema_version',
  'language_analyzers',
  'ignore',
  'diagnostics',
  'ownership',
  'multi_agent',
  'tools',
  'context',
  'graph',
  'memory',
];

/** Recursively list repo-relative file paths, skipping VCS/deps/noise/hidden. */
function walkFiles(root) {
  const out = [];
  const walk = (dir) => {
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (e.name === '.git' || e.name === 'node_modules' || e.name === '.acc' || e.name.startsWith('.')) continue;
      if (e.name === 'dist' || e.name === 'build' || e.name === 'coverage') continue;
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.isFile()) out.push(path.relative(root, full).split(path.sep).join('/'));
    }
  };
  walk(root);
  return out;
}

/** Language analyzer names for the languages present in the repo. */
function detectLanguages(root) {
  const present = new Set();
  for (const rel of walkFiles(root)) {
    const ext = path.posix.extname(rel).toLowerCase();
    for (const [name, exts] of Object.entries(ANALYZER_EXTS)) {
      if (exts.includes(ext)) {
        present.add(name);
        break;
      }
    }
  }
  return [...present].sort();
}

/** Ignore list for the generated config: standard noise + detected dirs. */
function detectIgnoredDirs(root) {
  const ignore = [...DEFAULT_IGNORE];
  for (const d of ['vendor', 'tmp', 'temp', 'out', 'target', 'venv', '.venv']) {
    if (fs.existsSync(path.join(root, d))) ignore.push(d);
  }
  return ignore;
}

/** Full config.yaml with every supported setting, project-aware. */
function generateConfigYaml(repoName, languages, ignore) {
  const langLines = (languages.length > 0 ? languages : ['rust', 'typescript', 'go', 'python'])
    .map((l) => `  ${l}: true`)
    .join('\n');
  const ignoreLines = ignore.map((d) => `  - ${d}`).join('\n');
  return `# ${repoName} — ACC configuration
#
# Generated by ABA (ACC Battle Arena) from the repository contents so every
# supported setting is present and matches the project. ACC works with
# sensible defaults when a setting is absent; see docs/03-repository-structure.md.
schema_version: 1

# Language analyzers are enabled for the languages actually present in the
# repository (used by acc check / acc graph).
language_analyzers:
${langLines}

# Directories excluded from ACC walks (VCS, dependencies, build noise).
ignore:
${ignoreLines}

diagnostics:
  # Example: downgrade a circular-reference warning to info:
  # warn_only: ["ACC014"]
  warn_only: []

ownership:
  strict: false

multi_agent:
  enabled: false
  max_concurrency: 4
  max_depth: 1
  task_timeout: 300
  resource_limits:
    cpu_percent: 80
    memory_mb: 4096
    token_budget: 1000000
  isolation_mode: git_worktree
  conflict_policy: sequentialize

tools:
  auto_discover: true
  defaults:
    filesystem: true
    search: true
    shell: true
    git: true
    project: true
    context: true
    graph: true
    memory: true
    check: true
  detected:
    enabled: true
  plugins:
    enabled: true
    directory: ".acc/config/tools"
  permissions:
    filesystem:
      read: true
      write: true
      glob: true
    shell:
      enabled: true
      approval: auto
      allowed_commands: []
    git:
      read: true
      write: true
    network:
      enabled: false

context:
  default_depth: 1
  default_max_bytes: 65536

graph:
  default_format: text
  default_provenance: true

memory:
  warn_bytes: 65536
  timestamp_format: rfc3339
`;
}

